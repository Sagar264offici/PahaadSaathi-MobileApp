/**
 * PAHAADSAATHI — NVIDIA AI Hazard Image Verification Types
 *
 * Defines the core types and data schemas for AI-powered photographic
 * evidence analysis using NVIDIA PaliGemma Vision API.
 */

export type AiVerificationStatus =
  | 'pending'
  | 'processing'
  | 'completed'
  | 'failed';

export type AiVerificationVerdict =
  | 'consistent'
  | 'partially_consistent'
  | 'inconsistent'
  | 'insufficient_evidence';

export type ImageQuality = 'good' | 'poor' | 'unclear';

export type AssessmentConfidence = 'not_determined' | 'suspected' | 'none';

/**
 * Structured output from NVIDIA PaliGemma Vision Analysis.
 * Strictly adheres to Section 5 of the Master Engineering Specification.
 */
export interface AiVerificationResult {
  /** Whether any physical hazard or obstruction is visible in the photograph */
  hazard_visible: boolean;

  /** The specific hazard detected from visual evidence (e.g. 'landslide', 'fallen_tree', 'flooding', 'none') */
  detected_hazard: string;

  /** The hazard category reported by the user */
  reported_hazard: string;

  /** The categorical verdict comparing photographic evidence to user claims */
  verdict: 'CONSISTENT' | 'PARTIALLY_CONSISTENT' | 'INCONSISTENT' | 'INSUFFICIENT_EVIDENCE';

  /** Whether the user's description is corroborated by visible details */
  description_match: boolean;

  /** Specific visible elements identified in the photograph */
  visual_evidence: string[];

  /** Contradictions between visual evidence and user description */
  contradictions: string[];

  /** Assessment of visual clarity and resolution */
  image_quality: ImageQuality;

  /** Preliminary check for obvious image reuse indicators */
  possible_image_reuse: AssessmentConfidence;

  /** Preliminary check for obvious digital manipulation */
  manipulation_indicators: AssessmentConfidence;

  /** Grounded, factual explanation of the comparison findings */
  explanation: string;

  /** Whether a human officer/moderator must inspect before official confirmation */
  human_review_recommended: boolean;

  /** Raw descriptive caption generated by NVIDIA PaliGemma */
  raw_caption?: string;

  /** Model identifier used for verification */
  model: string;

  /** ISO 8601 timestamp of analysis completion */
  verified_at: string;

  /** Execution latency in milliseconds */
  execution_time_ms?: number;
}

/**
 * Request payload to the verification service / Edge Function
 */
export interface VerifyHazardImageRequest {
  hazard_id: string;
  photo_url?: string | null;
  type?: string;
  description?: string;
  force?: boolean;
}

/**
 * Response payload from the verification service / Edge Function
 */
export interface VerifyHazardImageResponse {
  success: boolean;
  hazard_id: string;
  status: AiVerificationStatus;
  verdict?: AiVerificationVerdict;
  result?: AiVerificationResult;
  error_code?: string;
  message?: string;
}

/**
 * Display state representation for frontend UI components
 */
export type VerificationUiState =
  | 'pending'
  | 'analyzing'
  | 'consistent'
  | 'partially_consistent'
  | 'inconsistent'
  | 'insufficient_evidence'
  | 'failed';
